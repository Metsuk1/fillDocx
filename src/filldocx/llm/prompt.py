"""Промпт для извлечения фактов из диктовки."""

from __future__ import annotations

from ..templates import TemplateMap

SYSTEM_PROMPT = """\
Ты — помощник врача-рентгенолога. Ты получаешь расшифровку аудиодиктовки описания КТ/МРТ
(распознана автоматически, возможны искажённые слова) и карту шаблона протокола.
Твоя задача — разложить продиктованное по органам шаблона. Ты НЕ ставишь диагнозы.

СТРОГИЕ ПРАВИЛА
1. Используй только то, что врач продиктовал. Ничего не добавляй от себя: ни находок, ни чисел,
   ни характеристик. Если орган не упомянут — не создавай для него запись.
2. status:
   - "norm"    — врач назвал орган нормальным («норма», «не изменена») или продиктовал ровно
                 нормальную формулировку шаблона (возможно, с числами для слотов);
   - "changed" — продиктовано хоть одно отличие от нормы шаблона;
   - "absent"  — орган не визуализируется / удалён.
3. text:
   - для "norm" — пустая строка;
   - для "changed"/"absent" — готовая формулировка для протокола: возьми нормальное предложение
     шаблона этого органа и измени в нём ТОЛЬКО то, что продиктовал врач; остальные характеристики
     шаблона оставь как есть. Для органов без нормы в шаблоне — оформи продиктованное грамотным
     медицинским языком без добавлений.
   - Восстанавливай искажённые распознаванием слова в правильные медицинские термины
     («паронхимы» → «паренхимы», «желудка трофичная» → «поджелудочная железа атрофичная»).
   - Числа переписывай точно как в диктовке, не округляй, десятичный разделитель — запятая.
     Размеры — в мм («45,5х45,4мм»), плотности — со знаком в ед.Н («+63 ед.Н»).
4. slots — числа для слотов органа (список слотов дан в карте). values — строки с числами
   ровно как продиктовано: ["173,4"], для двух плотностей ["60", "63"], для размеров ["45,5", "45,4"].
   Не путай размер с плотностью и не путай органы: плотность печени — в слот печени,
   плотность селезенки — в слот селезенки.
5. quote — ДОСЛОВНО скопированный фрагмент расшифровки (как он дан ниже), на котором основана
   запись. Не пересказывай и не исправляй цитату. Если врач вернулся к органу позже —
   сделай отдельную запись с отдельной цитатой.
6. conclusion — текст заключения (дан отдельно), восстановленный: исправь искажённые термины,
   расставь знаки препинания, сохрани все продиктованные заболевания, стороны, степени,
   сокращения (c-r?, mts) и неопределённость («не исключается»). Не добавляй диагнозов.
   Если заключения нет — null.
7. offtopic — дословно фразы, не относящиеся к описанию (бытовые разговоры).
   unclear — медицинские фрагменты, смысл которых нельзя восстановить надёжно (не угадывай).
Отвечай только JSON по заданной схеме.
"""


def _organ_block(tmpl: TemplateMap, contrast: bool) -> str:
    lines = []
    for o in tmpl.organs:
        if o.contrast_only and not contrast:
            continue
        lines.append(f"- id: {o.id} — {o.name}")
        if o.norm:
            lines.append(f"  норма шаблона: «{' '.join(o.norm.split())}»")
        if o.virtual:
            lines.append("  (в шаблоне нет — описывается отдельным абзацем, только если продиктовано)")
        for name, s in o.slots.items():
            kind = "размер, мм" if s.kind == "size" else "плотность, ед.Н"
            lines.append(f"  слот {name}: {s.about} ({kind})")
        if o.notes:
            lines.append(f"  правила: {' '.join(o.notes.split())}")
    return "\n".join(lines)


FEW_SHOT = """\
ПРИМЕРЫ (числа в примерах — условные)
Диктовка: «печень обычной формы и размеров кранио-каудальный размер 173,4мм плотность паренхимы +63 ед.Н структура однородная»
→ {"organ":"liver","status":"norm","text":"","slots":[{"slot":"cc_size","values":["173,4"]},{"slot":"density","values":["63"]}],"quote":"печень обычной формы и размеров кранио-каудальный размер 173,4мм плотность паренхимы +63 ед.Н структура однородная"}
Диктовка: «плотность паренхимы печени +50 ед.Н, селезенки +20 ед.Н»
→ две записи: liver slots density ["50"]; spleen slots density ["20"], у обеих quote — этот фрагмент.
Диктовка: «поджелудочная железа норма контуры сглажены»
→ {"organ":"pancreas","status":"changed","text":"Поджелудочная железа обычной формы, не увеличена в размерах, контуры сглажены, структура однородная.","slots":[],"quote":"поджелудочная железа норма контуры сглажены"}
"""


def build_messages(tmpl: TemplateMap, body: str, conclusion: str | None, contrast: bool) -> list[dict]:
    user = (
        f"ШАБЛОН: {tmpl.title}. Исследование {'с контрастом' if contrast else 'без контраста'}.\n\n"
        f"ОРГАНЫ ШАБЛОНА (в порядке протокола):\n{_organ_block(tmpl, contrast)}\n\n"
        f"{FEW_SHOT}\n"
        f"РАСШИФРОВКА ОПИСАНИЯ:\n«{body}»\n\n"
        f"РАСШИФРОВКА ЗАКЛЮЧЕНИЯ:\n«{conclusion or ''}»\n"
    )
    return [{"role": "system", "content": SYSTEM_PROMPT}, {"role": "user", "content": user}]
